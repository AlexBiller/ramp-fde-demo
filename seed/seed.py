CUSTOMERS = ["Halcyon Freight", "Brightwater Foods", "Corvid Logistics", "Lumen Agritech", "Ostrava Medical"]
CITIES = ["Chicago", "Austin", "Seattle", "Atlanta", "Boston", "Phoenix"]

employees = []
for i in range(14):
    dept = DEPARTMENTS[i % len(DEPARTMENTS)]
    employees.append({
        "id": f"E-{101 + i}",
        "name": f"{FIRST[i]} {LAST[(i * 5) % len(LAST)]}",
        "department": dept,
        "title": rng.choice(TITLES[dept]),
    })

def emp(dept=None):
    pool = [e for e in employees if dept is None or e["department"] == dept]
    return rng.choice(pool)["id"]

START = date(2026, 9, 1)
def rand_date(lo=0, hi=52):
    return START + timedelta(days=rng.randint(lo, hi))

transactions, receipts, trips, eval_set = [], [], [], []
_tx = [1000]
_rc = [500]
_tr = [40]

def add_trip(employee_id, city, d, nights, purpose):
    _tr[0] += 1
    t = {"id": f"TRP-{_tr[0]}", "employee_id": employee_id, "city": city,
         "start": d.isoformat(), "end": (d + timedelta(days=nights)).isoformat(),
         "nights": nights, "purpose": purpose, "status": "approved"}
    trips.append(t)
    return t

def add_tx(employee_id, merchant_id, amount, memo, d, receipt=True, trip=None,
           label=None, note="", items=None):
    _tx[0] += 1
    txid = f"TX-{_tx[0]}"
    rid = None
    if receipt:
        _rc[0] += 1
        rid = f"RCP-{_rc[0]}"
        receipts.append({"id": rid, "txn_id": txid, "total": round(amount, 2),
                         "items": items or [{"desc": "Itemized charges", "amount": round(amount, 2)}],
                         "uploaded": (d + timedelta(days=rng.randint(0, 2))).isoformat()})
    transactions.append({"id": txid, "date": d.isoformat(), "employee_id": employee_id,
                         "merchant_id": merchant_id, "amount": round(amount, 2), "memo": memo,
                         "receipt_id": rid, "trip_id": trip["id"] if trip else None})
    if label:
        eval_set.append({"txn_id": txid, "label": label, "reviewer_note": note})
    return txid

def money(lo, hi):
    return round(rng.uniform(lo, hi), 2)

# --- Meals -----------------------------------------------------------------
