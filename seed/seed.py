#!/usr/bin/env python3
"""Generate the synthetic dataset used by the demo.

Every company, person, merchant, trip, receipt and transaction below is
fictional. The script is deterministic (fixed RNG seed) so the evaluation
numbers in the UI are reproducible.

Usage:  python3 seed/seed.py        -> writes data/seed.json and data/seed.js
"""
